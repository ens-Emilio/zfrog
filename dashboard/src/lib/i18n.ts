const DICTS: Record<Lang, Dict> = { en, pt, es }

let current: Lang =
  typeof document !== "undefined"
    ? ((document.documentElement.getAttribute("lang")?.slice(0, 2) as Lang) ?? "en")
    : "en"
if (current !== "pt" && current !== "en" && current !== "es") current = "en"

const listeners = new Set<() => void>()

function readLang(): Lang {
  try {
    const saved = localStorage.getItem("zfrog-lang")
    if (saved === "pt" || saved === "en" || saved === "es") return saved
  } catch {
    /* ignore */
  }
  const nav = (typeof navigator !== "undefined" ? navigator.language : "en").slice(0, 2).toLowerCase()
  if (nav === "pt" || nav === "es") return nav
  return "en"
}

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang) {
  current = lang
  applyLang(lang)
  listeners.forEach((fn) => fn())
}

/** Translate a key in the current language, falling back to English. */
export function t(key: I18nKey): string {
  return DICTS[current][key] ?? en[key]
}

function subscribe(fn: () => void) {
  listeners.add(fn)
  return () => {
    listeners.delete(fn)
  }
}

function getSnapshot(): Lang {
  return current
}

/** Re-render the component whenever the language changes. */
export function useT(): (key: I18nKey) => string {
  const lang = useSyncExternalStore(subscribe, getSnapshot, () => "en" as Lang)
  void lang
  return t
}

export function initLang(): Lang {
  current = readLang()
  applyLang(current)
  return current
}
